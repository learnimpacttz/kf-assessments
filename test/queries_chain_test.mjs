// The query approval chain: who may answer, review, approve and close
import { env, ok, done } from './_kit.mjs';
import { postQuery, flagKey } from '../src/queries.js';
import { STAFF } from '../src/config.js';
const vol = STAFF.find((s) => s.active && s.role === 'volunteer' && s.region === 'TANGA');
const rc = STAFF.find((s) => s.active && s.role === 'rc' && s.region === 'TANGA');
const rc2 = STAFF.find((s) => s.active && s.role === 'rc' && s.region === 'MARA');
const school = Object.values((await import('../src/config.js')).SCHOOL_BY_ID).find((s) => s.region === 'TANGA').id;
const key = flagKey({ type: 'slow', school, grade: 2, date: '2026-10-20', admin: vol.name });
const V = { role: 'volunteer', id: vol.id, name: vol.name, region: 'TANGA', position: vol.position };
const RC = { role: 'rc', id: rc.id, name: rc.name, region: 'TANGA', position: 'RC' };
const RC2 = { role: 'rc', id: rc2.id, name: rc2.name, region: 'MARA', position: 'RC' };
const joram = { role: 'hq', level: 'admin', name: 'Joram Joas', id: 'hq:h2', hq_id: 'h2', review_level: 2 };
const mundo = { role: 'hq', level: 'admin', name: 'Chogohe Edwin Mundo', id: 'hq:h1', hq_id: 'h1', review_level: 3 };
const call = (who, body) => postQuery(env, who, { key, ...body });
let r = await call(RC, { action: 'respond', text: 'I answer for the volunteer myself.' });
ok('an RC cannot answer first for a volunteer', r.error && r.status === 403, r.error);
r = await call(V, { action: 'respond', text: 'short' });
ok('a one-word reply is refused', r.error && r.status === 422);
r = await call(V, { action: 'respond', text: 'The pupil was slow because of a long story to read.' });
ok('the volunteer answers: it goes to team review', !r.error && r.q.wf.stage === 'team', r.error || r.q.wf.stage);
r = await call(V, { action: 'review', decision: 'approve' });
ok('the volunteer cannot review their own reply', Boolean(r.error));
r = await call(RC2, { action: 'review', decision: 'approve' });
ok('an RC of another region cannot review', Boolean(r.error));
r = await call(RC, { action: 'review', decision: 'approve' });
ok('the RC approves: it goes to the first HQ review', !r.error && r.q.wf.stage === 'hq1', r.error || '');
r = await call(mundo, { action: 'review', decision: 'approve' });
ok('Mundo cannot do the first HQ review', Boolean(r.error));
r = await call(joram, { action: 'resolve', text: 'close it' });
ok('Joram cannot close a query outside the chain', Boolean(r.error));
r = await call(mundo, { action: 'resolve', text: 'close it' });
ok('Mundo cannot close a query outside the chain', Boolean(r.error));
r = await call(joram, { action: 'review', decision: 'approve' });
ok('Joram approves: it goes to final approval', !r.error && r.q.wf.stage === 'final', r.error || '');
r = await call(joram, { action: 'review', decision: 'approve' });
ok('Joram cannot also give the final approval', Boolean(r.error));
r = await call(mundo, { action: 'review', decision: 'approve' });
ok('Mundo gives the final approval: approved and resolved', !r.error && r.q.wf.stage === 'approved' && r.q.status === 'resolved', r.error || '');
ok('the clearance alert names the people involved', r.notify && r.notify.to_stage === 'approved' && r.notify.people.length >= 3, JSON.stringify(r.notify && r.notify.people));
// reminders
const key2 = flagKey({ type: 'dup', school, grade: 1, date: '2026-10-21', admin: vol.name });
r = await postQuery(env, RC, { key: key2, action: 'remind' }); ok('an RC can remind a volunteer', !r.error, r.error || '');
r = await postQuery(env, RC, { key: key2, action: 'remind' }); ok('a second reminder within 4 hours is refused', r.error && r.status === 429, r.error || '');
r = await postQuery(env, V, { key: key2, action: 'remind' }); ok('a volunteer cannot send reminders', Boolean(r.error));
done();

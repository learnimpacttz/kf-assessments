import { env, ok, done } from './_kit.mjs';
import { levelGate, hqChange, hqByCode, hqList, loadHq, codeFor, ADVISOR_HIDE } from '../src/hq.js';
const admin = { role: 'hq', level: 'admin', hq_id: 'h3', name: 'M' };
await hqChange(env, admin, { action: 'add', name: 'Adv Isor', email: 'a@x.org', level: 'viewer', preset: 'advisor' });
const d = await loadHq(env, true); const u = d.users.find((x) => x.name === 'Adv Isor');
ok('advisor created with hidden list', u && u.hide.length === ADVISOR_HIDE.length);
const who = { role: 'hq', level: 'viewer', hide: u.hide, name: 'Adv' };
ok('questions blocked for advisor', levelGate(who, 'GET', '/api/ask') !== null);
ok('notes blocked', levelGate(who, 'GET', '/api/hqnotes') !== null);
ok('direct messages blocked', levelGate(who, 'GET', '/api/dm/sent') !== null);
ok('phones blocked', levelGate(who, 'GET', '/api/phones') !== null);
ok('bridge still readable', levelGate(who, 'GET', '/api/bridge') === null);
ok('overview still readable', levelGate(who, 'GET', '/api/overview') === null);
ok('a plain viewer is not blocked from questions', levelGate({ role: 'hq', level: 'viewer', hide: [] }, 'GET', '/api/ask') === null);
const code = await codeFor(env, u); ok('code works before the end date', (await hqByCode(env, code)) !== null);
await hqChange(env, admin, { action: 'update', id: u.id, expires_at: '2020-01-01' });
ok('expired access cannot sign in', (await hqByCode(env, code)) === null);
await hqChange(env, admin, { action: 'update', id: u.id, expires_at: '' });
ok('clearing the end date restores access', (await hqByCode(env, code)) !== null);
await hqChange(env, admin, { action: 'update', id: u.id, preset: 'full' });
ok('full access clears the hidden list', (await loadHq(env, true)).users.find((x) => x.id === u.id).hide.length === 0);
const ed = { role: 'hq', level: 'editor', hide: [], name: 'Ed' };
ok('editor can review queries', levelGate(ed, 'POST', '/api/query') === null);
ok('editor can message teams', levelGate(ed, 'POST', '/api/dm') === null);
ok('editor can answer field questions', levelGate(ed, 'POST', '/api/ask') === null);
ok('editor can write HQ notes', levelGate(ed, 'POST', '/api/hqnotes') === null);
ok('editor cannot open Admin', levelGate(ed, 'GET', '/api/admin/hq-users') !== null);
ok('editor cannot change corrections', levelGate(ed, 'POST', '/api/corrections') !== null);
ok('viewer still cannot send messages', levelGate({ role: 'hq', level: 'viewer', hide: [] }, 'POST', '/api/dm') !== null);
done();

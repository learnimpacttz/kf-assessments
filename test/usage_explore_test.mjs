import { env, ok, done } from './_kit.mjs';
import { recordUsage, usageExplore } from '../src/usage.js';
import { STAFF, eatToday } from '../src/config.js';
const vol = STAFF.find((s) => s.active && s.role === 'volunteer'), rc = STAFF.find((s) => s.active && s.role === 'rc');
const w = (s) => ({ role: s.role, name: s.name, region: s.region, id: s.id });
await recordUsage(env, w(vol), { tab: 'day', dev: 'm', ms: 60000, open: true });
await recordUsage(env, w(vol), { tab: 'work', dev: 'm', ms: 30000 });
await recordUsage(env, w(rc), { tab: 'allq', dev: 'd', ms: 120000, open: true });
const hq = { role: 'hq', name: 'T', level: 'admin' };
const r = await usageExplore(env, hq, {});
ok('explorer needs HQ', (await usageExplore(env, { role: 'rc' }, {})).error === 'HQ only');
ok('totals count views', r.totals.views === 3 && r.totals.people === 2, JSON.stringify(r.totals));
ok('today row has both people', r.days[r.days.length - 1].users === 2);
ok('tab usage listed', r.tabs.length === 3 && r.tabs.some((t) => t.tab === 'day'));
ok('heat has the hour', r.heat.flat().reduce((a, b) => a + b, 0) === 3);
const f = await usageExplore(env, hq, { role: 'volunteer' });
ok('role filter', f.totals.people === 1 && f.totals.views === 2);
const t = await usageExplore(env, hq, { tab: 'allq' });
ok('tab filter', t.totals.views === 1 && t.totals.people === 1);
const d = await usageExplore(env, hq, { dev: 'm' });
ok('device filter', d.totals.views === 2);
ok('funnel steps', r.funnel.length === 5 && r.funnel[2][1] === 2);
ok('person row status', r.people.find((p) => p.key === String(vol.id)).status === 'steady' || r.people.find((p) => p.key === String(vol.id)).status === 'rising');
done();
